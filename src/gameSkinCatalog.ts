function normalize(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]/g, "")
}

export function getSkinDisplayName(skinName: string): string {
  const pattern = skinName.match(/^(.*)_PATTERN_(\d+)$/i)
  if (pattern) {
    const family = pattern[1].replace(/_/g, " ")
    return `${family} Phase ${Number(pattern[2])}`
  }

  return skinName
    .replace(/_/g, " ")
    .replace(/\+/g, " + ")
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/([A-Za-z])(\d+)/g, "$1 $2")
    .replace(/(\d+)([A-Za-z])/g, "$1 $2")
    .replace(/\s+/g, " ")
    .trim()
}

export function resolveCatalogItemName(itemName: string): string {
  const wanted = normalize(itemName)
  const exactName = Object.keys(GAME_SKIN_CATALOG).find(
    (name) => normalize(name) === wanted,
  )
  if (!exactName) throw new Error(`No live skin catalog exists for ${itemName}`)
  return exactName
}

function resolveSkinName(
  itemName: string,
  skinName: string,
): string | undefined {
  const aliases = LEGACY_SKIN_ALIASES[itemName]
  const alias = aliases?.[normalize(skinName)]
  if (alias) return alias

  const wanted = normalize(skinName)
  return GAME_SKIN_CATALOG[itemName].find((name) => normalize(name) === wanted)
}

export function synchronizeSkins(
  itemName: string,
  currentSkins: readonly CatalogSkin[],
  placeholderImage: string,
  options: { omitStock?: boolean } = {},
): CatalogSkin[] {
  const exactItemName = resolveCatalogItemName(itemName)
  const imagesByExactName = new Map<string, string>()

  for (const skin of currentSkins) {
    const exactSkinName = resolveSkinName(exactItemName, skin.name)
    if (exactSkinName && !imagesByExactName.has(exactSkinName)) {
      imagesByExactName.set(exactSkinName, skin.img)
    }
  }

  return GAME_SKIN_CATALOG[exactItemName]
    .filter((name) => !(options.omitStock && name === "Stock"))
    .map((name) => ({
      name,
      displayName: getSkinDisplayName(name),
      img: imagesByExactName.get(name) || placeholderImage,
    }))
}

type WebsiteWeaponData = {
  name: string
  skins: CatalogSkin[]
  variants?: WebsiteWeaponData[]
}

type WebsiteCatalogData = {
  pistols: { weapons: WebsiteWeaponData[] }
  midTier: { weapons: WebsiteWeaponData[] }
  rifles: { weapons: WebsiteWeaponData[] }
  knifeTypes: WebsiteWeaponData[]
  glovesTypes: WebsiteWeaponData[]
}

export function synchronizeWebsiteData<T extends WebsiteCatalogData>(
  data: T,
  placeholderImage: string,
): T {
  function synchronizeWeapon(weapon: WebsiteWeaponData): void {
    weapon.name = resolveCatalogItemName(weapon.name)
    weapon.skins = synchronizeSkins(
      weapon.name,
      weapon.skins,
      placeholderImage,
      {
        omitStock: true,
      },
    )
    for (const variant of weapon.variants || []) synchronizeWeapon(variant)
  }

  for (const category of [data.pistols, data.midTier, data.rifles]) {
    for (const weapon of category.weapons) synchronizeWeapon(weapon)
  }
  for (const item of [...data.knifeTypes, ...data.glovesTypes]) {
    item.name = resolveCatalogItemName(item.name)
    item.skins = synchronizeSkins(item.name, item.skins, placeholderImage)
  }

  return data
}
